class VillasQatarApp extends StatefulWidget {
  const VillasQatarApp({super.key});

  @override
  State<VillasQatarApp> createState() => _VillasQatarAppState();
}

class _VillasQatarAppState extends State<VillasQatarApp> {
  // --------------------------------------------------------------------------
  // INIT
  // --------------------------------------------------------------------------

  @override
  void initState() {
    super.initState();

    // Initialize deep links after GetMaterialApp's navigator is available.
    WidgetsBinding.instance.addPostFrameCallback((_) {
      DeepLinkService.initialize();
    });
  }

  // --------------------------------------------------------------------------
  // DISPOSE
  // --------------------------------------------------------------------------

  @override
  void dispose() {
    DeepLinkService.dispose();
    super.dispose();
  }

  // --------------------------------------------------------------------------
  // SAVED LOCALE
  // --------------------------------------------------------------------------

  Locale? _savedLocale() {
    final String? saved = StorageService.getSavedLanguageOrNull();

    if (saved == 'ar') {
      return const Locale('ar', 'QA');
    }

    if (saved == 'en') {
      return const Locale('en', 'US');
    }

    return null;
  }

  // --------------------------------------------------------------------------
  // BUILD
  // --------------------------------------------------------------------------

  @override
  Widget build(BuildContext context) {
    return LayoutBuilder(
      builder: (context, constraints) {
        // ----------------------------------------------------------
        // Responsive Design Size
        // ----------------------------------------------------------

        final Size designSize;

        if (Responsive.isDesktop(context)) {
          designSize = const Size(1440, 1024);
        } else if (Responsive.isTablet(context)) {
          designSize = const Size(760, 1024);
        } else {
          designSize = const Size(394, 852);
        }

        // ----------------------------------------------------------
        // ScreenUtil
        // ----------------------------------------------------------

        return ScreenUtilInit(
          designSize: designSize,
          minTextAdapt: true,
          splitScreenMode: true,
          builder: (_, child) {
            return GetMaterialApp(
              // ----------------------------------------------------
              // Basic Configuration
              // ----------------------------------------------------
              debugShowCheckedModeBanner: false,

              onGenerateTitle: (_) => 'Villas Qatar'.tr,

              useInheritedMediaQuery: true,

              // ----------------------------------------------------
              // Localization
              // ----------------------------------------------------
              locale: DevicePreview.locale(context) ?? _savedLocale(),

              translations: AppTranslations(),

              fallbackLocale: const Locale('en', 'US'),

              // Direction-aware default transition: flips automatically
              // between LTR/RTL as the app locale changes.
              defaultTransition: AppTransitions.forward,

              supportedLocales: const [Locale('en', 'US'), Locale('ar', 'QA')],

              localizationsDelegates: const [
                GlobalMaterialLocalizations.delegate,
                GlobalWidgetsLocalizations.delegate,
                GlobalCupertinoLocalizations.delegate,
              ],

              // ----------------------------------------------------
              // App Builder
              // ----------------------------------------------------
              builder: (context, child) {
                child = DevicePreview.appBuilder(context, child);

                final Locale locale =
                    Get.locale ??
                    DevicePreview.locale(context) ??
                    const Locale('en', 'US');

                // Keep DateFormat/NumberFormat in step with the app language.
                Intl.defaultLocale = locale.languageCode;

                return Directionality(
                  textDirection: locale.languageCode == 'ar'
                      ? TextDirection.rtl
                      : TextDirection.ltr,
                  child: child ?? const SizedBox.shrink(),
                );
              },

              // ----------------------------------------------------
              // Theme
              // ----------------------------------------------------
              theme: AppTheme.lightTheme,

              // ----------------------------------------------------
              // Initial Screen
              // ----------------------------------------------------
              home: const SplashScreen(),
            );
          },
        );
      },
    );
  }
}
